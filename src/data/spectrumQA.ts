// 关键词命中计分：取最高分条目，零命中返回兜底
export function matchAnswer(q: string): string {
  const s = q.toLowerCase()
  let best = 0
  let bestA = ''
  QA_PAIRS.forEach(p => {
    const score = p.keys.reduce((n, k) => n + (s.includes(k.toLowerCase()) ? 1 : 0), 0)
    if (score > best) { best = score; bestA = p.a }
  })
  return bestA || QA_FALLBACK
}
